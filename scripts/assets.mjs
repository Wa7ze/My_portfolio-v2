// Asset pipeline. Run with `npm run assets`.
// 1. Converts every legacy raster image to WebP (same folder + basename) in two sizes:
//    full (max 1600px wide) and a 480px-wide thumbnail with a `-480` suffix.
// 2. Renders the <mm/> monogram icon set (favicon + manifest icons, same filenames as legacy).
// 3. Copies the CV PDF byte-for-byte.
// Legacy originals in ./legacy are read-only and never modified.
import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative } from 'node:path';
import sharp from 'sharp';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const legacyImages = join(root, 'legacy/assets/images');
const outImages = join(root, 'src/assets/images');
const publicDir = join(root, 'public');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])),
  );
  return files.flat();
}

async function convertImages() {
  // portfoilo-website/* now shows the NEW site: generated by scripts/portfolio-shots.mjs instead.
  const files = (await walk(legacyImages)).filter(
    (f) => /\.(png|jpe?g)$/i.test(f) && !/portfoilo-website/.test(f),
  );
  for (const file of files) {
    const rel = relative(legacyImages, file);
    const base = join(outImages, rel.slice(0, -extname(rel).length));
    await mkdir(dirname(base), { recursive: true });
    const meta = await sharp(file).metadata();
    await sharp(file)
      .resize({ width: Math.min(meta.width ?? 1600, 1600), withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(`${base}.webp`);
    await sharp(file)
      .resize({ width: 480, withoutEnlargement: true })
      .webp({ quality: 72 })
      .toFile(`${base}-480.webp`);
    console.log('webp', rel);
  }
}

// --- Monogram: amber angle brackets + slash, cyan "mm", on deep navy. Pure paths (no fonts),
// so it renders identically everywhere. `scale` shrinks the glyphs into the maskable safe zone.
function monogramSvg({ rounded, scale = 1 }) {
  const t = (256 * (1 - scale)).toFixed(1);
  const m = (x) =>
    `M${x} 324V252C${x} 214 ${x + 47} 214 ${x + 47} 252V324M${x + 47} 252C${x + 47} 214 ${x + 94} 214 ${x + 94} 252V324`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#16233F"/>
      <stop offset="1" stop-color="#0B1426"/>
    </linearGradient>
  </defs>
  <rect width="512" height="512" rx="${rounded ? 112 : 0}" fill="url(#bg)"/>
  ${rounded ? '<rect x="6" y="6" width="500" height="500" rx="106" fill="none" stroke="#3DE0FF" stroke-opacity="0.35" stroke-width="6"/>' : ''}
  <g transform="translate(${t} ${t}) scale(${scale})" fill="none" stroke-linecap="round" stroke-linejoin="round">
    <path d="M96 186L44 256L96 326" stroke="#FFB547" stroke-width="32"/>
    <path d="${m(118)}${m(224)}" stroke="#3DE0FF" stroke-width="20"/>
    <path d="M384 180L346 332" stroke="#FFB547" stroke-width="28"/>
    <path d="M416 186L468 256L416 326" stroke="#FFB547" stroke-width="32"/>
  </g>
</svg>`;
}

async function renderIcons() {
  await mkdir(join(publicDir, 'icons'), { recursive: true });
  const standard = monogramSvg({ rounded: true });
  const maskable = monogramSvg({ rounded: false, scale: 0.72 });
  await writeFile(join(publicDir, 'favicon.svg'), standard);
  const jobs = [
    ['favicon.png', standard, 32],
    ['icons/Icon-192.png', standard, 192],
    ['icons/Icon-512.png', standard, 512],
    ['icons/Icon-maskable-192.png', maskable, 192],
    ['icons/Icon-maskable-512.png', maskable, 512],
  ];
  for (const [name, svg, size] of jobs) {
    await sharp(Buffer.from(svg), { density: 300 }).resize(size, size).png().toFile(join(publicDir, name));
    console.log('icon', name);
  }
}

await mkdir(publicDir, { recursive: true });
await convertImages();
await renderIcons();
await copyFile(join(root, 'legacy/web/cv.pdf'), join(publicDir, 'cv.pdf'));
console.log('copied cv.pdf');
